//! `tatara-rust-docs` — the catalog **is** the documentation source of truth.
//!
//! The macro farm already treats every repeating impl as a typed Spec
//! and emits the proc-macro crate mechanically (★★ EMITTER SUBSTRATE).
//! This crate closes the loop on the *other* artifact every published
//! derive needs — its documentation — by rendering it from the same
//! [`MacroCatalogSpec`]. The fleet stops hand-maintaining a docs table
//! that drifts from the catalog (the 2026-05-28 `macro-farm.md` listed
//! 15 derives while the catalog had grown to 26).
//!
//! Three artifacts, all in pleme-io house style, all regenerated by one
//! command so they can never drift from the catalog:
//!
//! | Artifact | House style | Audience |
//! |---|---|---|
//! | [`DocBundle::reference_md`] | `./docs/` reference table | humans browsing the family |
//! | [`DocBundle::claude_fragment_md`] | `CLAUDE.md` ★★ section | agents loading repo context |
//! | [`DocBundle::skill_md`] | `skills/<name>/SKILL.md` | agents deciding *when* to reach for a derive |
//!
//! This is the typescape discipline applied to prose: a typed source
//! (`MacroCatalogSpec`) rendered to a target artifact (markdown), with a
//! reflection test (`reference lists every entry`) that makes drift a
//! compile-time-detectable error instead of a documentation rot.
//!
//! Pure rendering (`render_*`) is I/O-free; [`write_bundle`] is the only
//! function that touches disk.

use std::io;
use std::path::Path;

use tatara_rust_catalog::{CatalogEntry, MacroCatalogSpec};

/// The regeneration provenance stamped into every artifact so a reader
/// (human or agent) knows it is generated and how to refresh it.
const REGEN_HINT: &str =
    "tatara-rust-forge catalog-emit-docs catalogs/pleme-derives.lisp --out .";

/// A complete documentation bundle rendered from one catalog.
#[derive(Clone, Debug)]
pub struct DocBundle {
    /// `./docs/derives-reference.md` — the canonical family table.
    pub reference_md: String,
    /// A `CLAUDE.md` ★★ section — repo context for agents.
    pub claude_fragment_md: String,
    /// `skills/consume-pleme-derives/SKILL.md` — when-to-use guidance.
    pub skill_md: String,
}

/// Render every house-style doc artifact for a catalog. Pure — no I/O.
pub fn render_docs(catalog: &MacroCatalogSpec) -> DocBundle {
    DocBundle {
        reference_md: render_reference(catalog),
        claude_fragment_md: render_claude_fragment(catalog),
        skill_md: render_skill(catalog),
    }
}

/// Write a [`DocBundle`] to the standard pleme-io layout under `out`:
///
/// ```text
/// <out>/docs/derives-reference.md
/// <out>/docs/CLAUDE-derives-fragment.md
/// <out>/skills/consume-pleme-derives/SKILL.md
/// ```
pub fn write_bundle(bundle: &DocBundle, out: &Path) -> io::Result<Vec<std::path::PathBuf>> {
    let docs_dir = out.join("docs");
    let skill_dir = out.join("skills").join("consume-pleme-derives");
    std::fs::create_dir_all(&docs_dir)?;
    std::fs::create_dir_all(&skill_dir)?;

    let reference = docs_dir.join("derives-reference.md");
    let claude = docs_dir.join("CLAUDE-derives-fragment.md");
    let skill = skill_dir.join("SKILL.md");

    std::fs::write(&reference, &bundle.reference_md)?;
    std::fs::write(&claude, &bundle.claude_fragment_md)?;
    std::fs::write(&skill, &bundle.skill_md)?;

    Ok(vec![reference, claude, skill])
}

