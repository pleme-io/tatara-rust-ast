// Helpers
// ─────────────────────────────────────────────────────────────────────

fn run(program: &str, args: &[&str], cwd: &Path) -> std::io::Result<Output> {
    Command::new(program)
        .args(args)
        .current_dir(cwd)
        .stderr(Stdio::piped())
        .stdout(Stdio::piped())
        .output()
}

/// Truncate `s` to at most `max` chars on a UTF-8 char boundary. Used to
/// fit a catalog description into GitHub's 350-char repo-description limit
/// without panicking on multi-byte boundaries (descriptions contain `—`,
/// `…`, etc.). Returns `s` unchanged when already within `max`.
fn cap_chars(s: &str, max: usize) -> String {
    match s.char_indices().nth(max) {
        None => s.to_owned(),
        Some((byte_idx, _)) => s[..byte_idx].to_owned(),
    }
}

fn failed_from(full_name: &str, step: PublishStep, out: &Output) -> PublishOutcome {
    PublishOutcome::Failed {
        full_name: full_name.into(),
        step,
        exit: out.status.code(),
        stderr: String::from_utf8_lossy(&out.stderr).into_owned(),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn step_labels_are_stable() {
        assert_eq!(PublishStep::GitInit.label(), "git-init");
        assert_eq!(PublishStep::GhRepoCreate.label(), "gh-repo-create");
    }

    #[test]
    fn cap_chars_respects_limit_and_char_boundaries() {
        assert_eq!(cap_chars("short", 350), "short");
        // Exactly at the limit is unchanged.
        let s40 = "a".repeat(40);
        assert_eq!(cap_chars(&s40, 40), s40);
        // Over the limit truncates to `max` chars.
        let s400 = "b".repeat(400);
        assert_eq!(cap_chars(&s400, 350).chars().count(), 350);
        // Multi-byte chars never split mid-codepoint (would panic on a
        // byte-index slice). Each `—` is 3 bytes; cap at 2 chars = 6 bytes.
        assert_eq!(cap_chars("—————", 2), "——");
    }

    #[test]
    fn visibility_flags_match_gh_cli_surface() {
        assert_eq!(RepoVisibility::Public.gh_flag(), "--public");
        assert_eq!(RepoVisibility::Private.gh_flag(), "--private");
        assert_eq!(RepoVisibility::Internal.gh_flag(), "--internal");
    }

    #[test]
    fn outcome_is_success_inspects_variant() {
        assert!(PublishOutcome::Created {
            full_name: "x/y".into()
        }
        .is_success());
        assert!(PublishOutcome::Updated {
            full_name: "x/y".into(),
            commits_pushed: 1
        }
        .is_success());
        assert!(PublishOutcome::UpToDate {
            full_name: "x/y".into()
        }
        .is_success());
        assert!(!(PublishOutcome::Skipped {
            full_name: "x/y".into(),
            reason: "no cargo".into()
        })
        .is_success());
        assert!(!(PublishOutcome::Failed {
            full_name: "x/y".into(),
            step: PublishStep::GitInit,
            exit: Some(1),
            stderr: String::new()
        })
        .is_success());
    }

    #[test]
    fn default_commit_message_uses_short_name() {
        let s = RepoPublishSpec {
            path: PathBuf::from("/tmp"),
            full_name: "pleme-io/foo-derive".into(),
            description: "x".into(),
            commit_message: None,
        };
        assert_eq!(
            s.commit_message(),
            "init: foo-derive (generated by tatara-rust-ast)"
        );
    }

    #[test]
    fn custom_commit_message_overrides_default() {
        let s = RepoPublishSpec {
            path: PathBuf::from("/tmp"),
            full_name: "pleme-io/foo-derive".into(),
            description: "x".into(),
            commit_message: Some("my msg".into()),
        };
        assert_eq!(s.commit_message(), "my msg");
    }

    #[test]
    fn skipped_missing_path_returns_skipped() {
        let s = RepoPublishSpec {
            path: PathBuf::from("/nonexistent/path/that/does/not/exist"),
            full_name: "x/y".into(),
            description: "x".into(),
            commit_message: None,
        };
        let cfg = PublishConfig::default();
        let oc = publish_repo(&s, &cfg).unwrap();
        assert!(matches!(
            oc,
            PublishOutcome::Skipped { reason, .. } if reason.contains("does not exist")
        ));
    }

    #[test]
    fn skipped_no_cargo_toml_returns_skipped() {
        let tmp = std::env::temp_dir().join(format!("tatara-publish-no-cargo-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&tmp);
        std::fs::create_dir_all(&tmp).unwrap();
        let s = RepoPublishSpec {
            path: tmp.clone(),
            full_name: "x/y".into(),
            description: "x".into(),
            commit_message: None,
        };
        let cfg = PublishConfig::default();
        let oc = publish_repo(&s, &cfg).unwrap();
        assert!(matches!(
            oc,
            PublishOutcome::Skipped { reason, .. } if reason.contains("Cargo.toml")
        ));
        let _ = std::fs::remove_dir_all(&tmp);
    }

    #[test]
    fn batch_empty_input_succeeds() {
        let cfg = PublishConfig::default();
        let b = publish_all(&[], &cfg).unwrap();
        assert!(b.all_succeeded());
        assert_eq!(b.success_count(), 0);
        assert_eq!(b.failed_count(), 0);
        assert!(!b.stopped_at_failure);
    }
}
