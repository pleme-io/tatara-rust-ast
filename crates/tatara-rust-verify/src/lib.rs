//! `tatara-rust-verify` — auto-emit a `consumer-verify/` crate per
//! `MacroCatalogSpec`. The catalog's own verification harness is
//! itself generated — every emitted derive proves itself in a
//! `cargo test` run alongside the N decorated repos.
//!
//! Per-kind verifier strategy:
//!   - `Derive` (simple marker)       → struct with `#[derive(Trait)]`
//!                                      asserts it compiles.
//!   - `PerField` (getter/setter/builder) → struct with 2 fields,
//!                                      `#[derive(Trait)]`, calls each
//!                                      generated method.
//!   - `PerVariant` (predicate)       → enum with 3 variants,
//!                                      `#[derive(Trait)]`, calls each
//!                                      predicate.
//!   - `ProcAttr` / `ProcFn` / `MacroRules` / `Composite`
//!                                    → MVP: emit `let _ = …;` smoke
//!                                      that proves the macro is
//!                                      importable. Specialized
//!                                      verifiers land as follow-up
//!                                      per-kind variants.

use tatara_rust_ast::{CrateScaffold, FileEntry};
use tatara_rust_catalog::{CatalogEntry, CatalogSpec, MacroCatalogSpec, VerifierHint};
use tatara_rust_derive::{
    EnumFoldDeriveSpec, NewtypeDeriveSpec, PerFieldDeriveSpec, PerVariantDeriveSpec,
};

/// Render a complete `consumer-verify/` Cargo crate scaffold. The
/// caller writes it next to the N decorated repos so that
/// `cargo test -p consumer-verify` exercises every emitted derive.
///
/// `repo_path_template` maps each entry's crate name to the path
/// string the consumer's `Cargo.toml` should use to reach the
/// generated repo — typically `format!("../{name}")` when consumer
/// sits as a workspace member next to the repos.
#[must_use]
pub fn build_consumer_verify(
    catalog: &MacroCatalogSpec,
    repo_path_template: impl Fn(&str) -> String,
) -> CrateScaffold {
    let mut s = CrateScaffold::new("consumer-verify", "0.1.0");
    s.add_file("Cargo.toml", render_cargo_toml(catalog, &repo_path_template));
    s.add_file("src/lib.rs", render_lib_rs(catalog));
    s
}

/// Just the lib.rs body — useful for snapshot tests + diagnostics.
#[must_use]
pub fn render_lib_rs(catalog: &MacroCatalogSpec) -> String {
    let mut out = String::new();
    out.push_str("//! Generated by tatara-rust-verify — exercises every\n");
    out.push_str("//! macro in the catalog. One test module per entry.\n");
    out.push_str("//!\n");
    out.push_str("//! This file is RE-GENERATED on every catalog instantiate;\n");
    out.push_str("//! do not edit by hand.\n\n");

    for entry in &catalog.entries {
        out.push_str(&render_entry_module(entry));
        out.push('\n');
    }
    out
}

fn render_entry_module(entry: &CatalogEntry) -> String {
    let mod_name = entry.crate_name.replace('-', "_");
    let mut out = String::new();
    out.push_str(&format!(
        "/// Verifier for catalog entry `{}` (kind: {}).\n",
        entry.crate_name,
        entry.spec.kind_label()
    ));
    out.push_str(&format!("pub mod {mod_name} {{\n"));
    out.push_str(&render_per_kind_body(entry));
    out.push_str("}\n");
    out
}

fn render_per_kind_body(entry: &CatalogEntry) -> String {
    let extern_name = entry.crate_name.replace('-', "_");

    // **Explicit hint takes precedence.** Removes the fragility of
    // template-text substring matching for catalogs that opt in.
    if let Some(hint) = entry.verifier_hint {
        let trait_name = entry.spec.trait_name_for_verifier().unwrap_or("Unknown");
        return render_by_hint(hint, &extern_name, trait_name);
    }

    // Back-compat path: infer from spec shape + template text.
    match &entry.spec {
        CatalogSpec::Derive { spec } => render_marker_smoke(&extern_name, &spec.trait_name.0),
        CatalogSpec::PerField { spec } => render_per_field_smoke(&extern_name, spec),
        CatalogSpec::PerVariant { spec } => render_per_variant_smoke(&extern_name, spec),
        CatalogSpec::Newtype { spec } => render_newtype_smoke(&extern_name, spec),
        CatalogSpec::EnumFold { spec } => render_enum_fold_smoke(&extern_name, spec),
        CatalogSpec::ProcAttr { spec } => {
            render_proc_attr_smoke(&extern_name, &spec.macro_name.0)
        }
        CatalogSpec::ProcFn { spec } => {
            render_proc_fn_smoke(&extern_name, &spec.macro_name.0)
        }
        CatalogSpec::MacroRules { spec } => {
            render_macro_rules_smoke(&extern_name, &spec.macro_name.0)
        }
        CatalogSpec::Composite { spec } => {
            render_marker_smoke(&extern_name, &spec.bundle_name.0)
        }
    }
}

