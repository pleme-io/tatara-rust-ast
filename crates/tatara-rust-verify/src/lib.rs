fn render_compile_only_smoke(extern_name: &str, trait_name: &str) -> String {
    // Don't know what methods get generated — at least prove the
    // derive expands and the resulting impl block compiles.
    format!(
        r#"    use {extern_name}::{trait_name};

    #[derive({trait_name})]
    pub struct Sample {{
        pub a: i32,
    }}

    #[cfg(test)]
    mod tests {{
        use super::*;
        #[test]
        fn derive_compiles() {{
            let _ = Sample {{ a: 0 }};
        }}
    }}
"#
    )
}

fn render_enum_fold_smoke(extern_name: &str, spec: &EnumFoldDeriveSpec) -> String {
    let trait_name = &spec.trait_name.0;
    let tpl = spec.fold_template.to_lowercase();
    if tpl.contains("const all") && tpl.contains("&[#fold]") {
        render_all_variants_smoke(extern_name, trait_name)
    } else if tpl.contains("const count") && tpl.contains("#fold_count") {
        render_variant_count_smoke(extern_name, trait_name)
    } else if tpl.contains("const names") {
        render_variant_names_smoke(extern_name, trait_name)
    } else {
        render_enum_fold_compile_only(extern_name, trait_name)
    }
}

