// ─────────────────────────────────────────────────────────────────────

fn render_cargo_toml<F>(catalog: &MacroCatalogSpec, repo_path: &F) -> String
where
    F: Fn(&str) -> String,
{
    let mut m = CargoManifest::new(
        Package {
            name: "consumer-verify".into(),
            version: "0.1.0".into(),
            edition: "2024".into(),
            license: "MIT".into(),
            description: format!("Auto-generated verifier for the {} catalog.", catalog.title),
        },
        Some(Lib {
            proc_macro: None,
            path: Some("src/lib.rs".into()),
        }),
    );
    // One path dep per catalog entry.
    for e in &catalog.entries {
        m.add_dep(
            e.crate_name.clone(),
            Dep::Detailed(DetailedDep::path(repo_path(&e.crate_name))),
        );
    }
    // When any entry is a ClosedAxis, the emitted derive references
    // `impl ::shikumi::ClosedAxis`; edition-2018 `::shikumi` resolves
    // against imported crates, so the verify crate needs shikumi as an
    // extern crate to compile + exercise the trait half.
    let needs_shikumi = catalog
        .entries
        .iter()
        .any(|e| matches!(e.spec, CatalogSpec::ClosedAxis { .. }));
    if needs_shikumi {
        m.add_dep(
            "shikumi",
            Dep::Detailed(DetailedDep::git("https://github.com/pleme-io/shikumi")),
        );
    }
    m.to_toml()
        .expect("consumer-verify Cargo manifest is all-string keys; toml::to_string cannot fail")
}

