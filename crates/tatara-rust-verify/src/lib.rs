    #[test]
    fn classify_template_recognises_canonical_shapes() {
        assert!(matches!(
            classify_per_field_template(
                "pub fn #field_name(&self) -> &#field_ty { &self.#field_name }",
                None
            ),
            PerFieldStrategy::Getter
        ));
        assert!(matches!(
            classify_per_field_template(
                "pub fn #method_ident(mut self, v: #field_ty) -> Self { self.#field_name = v; self }",
                Some("with_{}")
            ),
            PerFieldStrategy::WithBuilder { .. }
        ));
        assert!(matches!(
            classify_per_field_template(
                "pub fn #method_ident(&mut self, v: #field_ty) { self.#field_name = v; }",
                Some("set_{}")
            ),
            PerFieldStrategy::Setter { .. }
        ));
        assert!(matches!(
            classify_per_field_template(
                "pub fn #method_ident(&mut self) -> &mut #field_ty { &mut self.#field_name }",
                Some("{}_mut")
            ),
            PerFieldStrategy::AsMut { .. }
        ));
        assert!(matches!(
            classify_per_field_template(
                "pub fn #method_ident(&mut self, v: #field_ty) -> #field_ty { ::std::mem::replace(&mut self.#field_name, v) }",
                Some("replace_{}")
            ),
            PerFieldStrategy::Replace { .. }
        ));
        assert!(matches!(
            classify_per_field_template(
                "pub fn #method_ident(&mut self) -> #field_ty where #field_ty: ::std::default::Default { ::std::mem::take(&mut self.#field_name) }",
                Some("take_{}")
            ),
            PerFieldStrategy::Take { .. }
        ));
        assert!(matches!(
            classify_per_field_template("// noise", None),
            PerFieldStrategy::Unknown
        ));
    }
