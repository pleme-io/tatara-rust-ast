//! `tatara-rust-verify` — auto-emit a `consumer-verify/` crate per
//! `MacroCatalogSpec`. The catalog's own verification harness is
//! itself generated — every emitted derive proves itself in a
//! `cargo test` run alongside the N decorated repos.
//!
//! **★★ TYPED EMISSION.** Every smoke renderer builds a
//! `proc_macro2::TokenStream` via `quote!{}`; the umbrella `lib.rs` is
//! assembled from those module token streams and rendered through ONE
//! chokepoint — [`render_file`] (`syn::parse2::<syn::File>` +
//! `prettyplease::unparse`). No `format!()`/`push_str` of Rust syntax
//! remains. The `Cargo.toml` is built as a typed
//! [`tatara_rust_ast::CargoManifest`] and serialized via `toml::to_string`.
//!
//! Per-kind verifier strategy:
//!   - `Derive` (simple marker)       → struct with `#[derive(Trait)]`
//!                                      asserts it compiles.
//!   - `PerField` (getter/setter/builder) → struct with 2 fields,
//!                                      `#[derive(Trait)]`, calls each
//!                                      generated method.
//!   - `PerVariant` (predicate)       → enum with 3 variants,
//!                                      `#[derive(Trait)]`, calls each
//!                                      predicate.
//!   - `ProcAttr` / `ProcFn` / `MacroRules` / `Composite`
//!                                    → MVP: emit `let _ = …;` smoke
//!                                      that proves the macro is
//!                                      importable. Specialized
//!                                      verifiers land as follow-up
//!                                      per-kind variants.

use proc_macro2::TokenStream;
use quote::{format_ident, quote};
use tatara_rust_ast::cargo_manifest::{CargoManifest, Dep, DetailedDep, Lib, Package};
use tatara_rust_ast::{CrateScaffold, FileEntry};
use tatara_rust_catalog::{CatalogEntry, CatalogSpec, MacroCatalogSpec, VerifierHint};
use tatara_rust_derive::{
    ClosedAxisSpec, EnumFoldDeriveSpec, KindRoundTripSpec, NewtypeDeriveSpec, PerFieldDeriveSpec,
    PerVariantDeriveSpec, VerificationMatrixSpec,
};

/// Render a complete `consumer-verify/` Cargo crate scaffold. The
/// caller writes it next to the N decorated repos so that
/// `cargo test -p consumer-verify` exercises every emitted derive.
///
/// `repo_path_template` maps each entry's crate name to the path
/// string the consumer's `Cargo.toml` should use to reach the
/// generated repo — typically `format!("../{name}")` when consumer
/// sits as a workspace member next to the repos.
#[must_use]
pub fn build_consumer_verify(
    catalog: &MacroCatalogSpec,
    repo_path_template: impl Fn(&str) -> String,
) -> CrateScaffold {
    let mut s = CrateScaffold::new("consumer-verify", "0.1.0");
    s.add_file("Cargo.toml", render_cargo_toml(catalog, &repo_path_template));
    s.add_file("src/lib.rs", render_lib_rs(catalog));
    s
}

