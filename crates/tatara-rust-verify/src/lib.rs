fn render_per_field_smoke(extern_name: &str, spec: &PerFieldDeriveSpec) -> TokenStream {
    let trait_name = &spec.trait_name.0;
    let template = &spec.per_field_template;
    let method_tpl = spec.method_name_template.as_deref();

    // Three method-shape strategies cover the canonical Tier-1 derives.
    // Each strategy explicitly knows what the generated methods look
    // like and asserts they behave; the strategy is selected on the
    // method-name-template + template-body shape.
    let strategy = classify_per_field_template(template, method_tpl);
    match strategy {
        PerFieldStrategy::Getter => render_getter_smoke(extern_name, trait_name),
        PerFieldStrategy::Setter { .. } => render_setter_smoke(extern_name, trait_name),
        PerFieldStrategy::WithBuilder { .. } => render_with_builder_smoke(extern_name, trait_name),
        PerFieldStrategy::AsMut { .. } => render_asmut_smoke(extern_name, trait_name),
        PerFieldStrategy::Replace { .. } => render_replace_smoke(extern_name, trait_name),
        PerFieldStrategy::Take { .. } => render_take_smoke(extern_name, trait_name),
        PerFieldStrategy::Unknown => render_compile_only_smoke(extern_name, trait_name),
    }
}

#[derive(Debug)]
enum PerFieldStrategy {
    /// `pub fn <field>(&self) -> &<T>` — borrowed read.
    Getter,
    /// `pub fn set_<field>(&mut self, v: <T>)` — overwrite.
    Setter { method_tpl: String },
    /// `pub fn with_<field>(mut self, v: <T>) -> Self` — fluent builder.
    WithBuilder { method_tpl: String },
    /// `pub fn <field>_mut(&mut self) -> &mut <T>` — mutable borrow.
    AsMut { method_tpl: String },
    /// `pub fn replace_<field>(&mut self, v: <T>) -> <T>` — swap.
    Replace { method_tpl: String },
    /// `pub fn take_<field>(&mut self) -> <T>` — steal-with-default.
    Take { method_tpl: String },
    /// Template doesn't match any known shape — verifier falls back to
    /// a compile-only smoke that proves the derive expands.
    Unknown,
}

fn classify_per_field_template(template: &str, method_tpl: Option<&str>) -> PerFieldStrategy {
    let body = template.to_lowercase();
    match method_tpl {
        None if body.contains("-> &") && body.contains("&self") => PerFieldStrategy::Getter,
        Some(t) if t.starts_with("with_") && body.contains("-> self") => {
            PerFieldStrategy::WithBuilder {
                method_tpl: t.to_string(),
            }
        }
        Some(t) if t.starts_with("set_") && body.contains("&mut self") => {
            PerFieldStrategy::Setter {
                method_tpl: t.to_string(),
            }
        }
        Some(t) if t.starts_with("replace_") && body.contains("mem::replace") => {
            PerFieldStrategy::Replace {
                method_tpl: t.to_string(),
            }
        }
        Some(t) if t.starts_with("take_") && body.contains("mem::take") => {
            PerFieldStrategy::Take {
                method_tpl: t.to_string(),
            }
        }
        Some(t) if t.ends_with("_mut") && body.contains("-> &mut") => PerFieldStrategy::AsMut {
            method_tpl: t.to_string(),
        },
        _ => PerFieldStrategy::Unknown,
    }
}

