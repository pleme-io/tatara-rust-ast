/// Render a `TokenStream` of crate-level items into a formatted source
/// string. Parses through `syn::File` (so malformed emission is a
/// compile-time-of-the-emitter panic, not silent garbage), then
/// `prettyplease::unparse`. The ★★ TYPED EMISSION single render surface.
fn render_file(items: TokenStream) -> String {
    let parsed: syn::File =
        syn::parse2(items).expect("emitted consumer-verify lib.rs must parse as syn::File");
    prettyplease::unparse(&parsed)
}

/// Just the lib.rs body — useful for snapshot tests + diagnostics.
#[must_use]
pub fn render_lib_rs(catalog: &MacroCatalogSpec) -> String {
    let modules: Vec<TokenStream> = catalog.entries.iter().map(render_entry_module).collect();
    let file = quote! {
        #![doc = "Generated by tatara-rust-verify — exercises every macro in the catalog."]
        #![doc = "One test module per entry."]
        #![doc = ""]
        #![doc = "This file is RE-GENERATED on every catalog instantiate; do not edit by hand."]

        #(#modules)*
    };
    render_file(file)
}

fn render_entry_module(entry: &CatalogEntry) -> TokenStream {
    let mod_ident = format_ident!("{}", entry.crate_name.replace('-', "_"));
    let doc = format!(
        "Verifier for catalog entry `{}` (kind: {}).",
        entry.crate_name,
        entry.spec.kind_label()
    );
    let body = render_per_kind_body(entry);
    quote! {
        #[doc = #doc]
        pub mod #mod_ident {
            #body
        }
    }
}

fn render_per_kind_body(entry: &CatalogEntry) -> TokenStream {
    let extern_name = entry.crate_name.replace('-', "_");

    // **Explicit hint takes precedence.** Removes the fragility of
    // template-text substring matching for catalogs that opt in.
    if let Some(hint) = entry.verifier_hint {
        let trait_name = entry.spec.trait_name_for_verifier().unwrap_or("Unknown");
        return render_by_hint(hint, &extern_name, trait_name);
    }

    // Back-compat path: infer from spec shape + template text.
    match &entry.spec {
        CatalogSpec::Derive { spec } => render_marker_smoke(&extern_name, &spec.trait_name.0),
        CatalogSpec::PerField { spec } => render_per_field_smoke(&extern_name, spec),
        CatalogSpec::PerVariant { spec } => render_per_variant_smoke(&extern_name, spec),
        CatalogSpec::Newtype { spec } => render_newtype_smoke(&extern_name, spec),
        CatalogSpec::EnumFold { spec } => render_enum_fold_smoke(&extern_name, spec),
        CatalogSpec::ProcAttr { spec } => render_proc_attr_smoke(&extern_name, &spec.macro_name.0),
        CatalogSpec::ProcFn { spec } => render_proc_fn_smoke(&extern_name, &spec.macro_name.0),
        CatalogSpec::MacroRules { spec } => {
            render_macro_rules_smoke(&extern_name, &spec.macro_name.0)
        }
        CatalogSpec::Composite { spec } => render_marker_smoke(&extern_name, &spec.bundle_name.0),
        CatalogSpec::KindRoundTrip { spec } => render_kind_round_trip_smoke(&extern_name, spec),
        CatalogSpec::VerificationMatrix { spec } => {
            render_verification_matrix_smoke(&extern_name, spec)
        }
        CatalogSpec::ClosedAxis { spec } => render_closed_axis_smoke(&extern_name, spec),
    }
}

/// Smoke test for a ClosedAxis derive: a unit enum with the
/// `Copy + Eq + Hash` bounds the `shikumi::ClosedAxis` trait requires,
/// `#[derive(ClosedAxis)]`, then asserts BOTH halves of the derive
/// output — the inherent `Self::ALL` AND the `impl ::shikumi::ClosedAxis`
/// associated `ALL`. The umbrella `Cargo.toml` now carries the shikumi
/// git dep (added by [`render_cargo_toml`] when any entry is a
/// `ClosedAxis`), so this gate proves the FULL derive, not just the
/// inherent constant.
fn render_closed_axis_smoke(extern_name: &str, spec: &ClosedAxisSpec) -> TokenStream {
    let extern_id = format_ident!("{extern_name}");
    let trait_id = format_ident!("{}", spec.trait_name.0);
    quote! {
        use #extern_id::#trait_id;

        #[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, #trait_id)]
        pub enum Sample {
            Block,
            Bar,
            Underline,
        }

        #[cfg(test)]
        mod tests {
            use super::*;
            #[test]
            fn inherent_all_enumerates_every_variant() {
                assert_eq!(Sample::ALL.len(), 3);
                assert!(Sample::ALL.iter().any(|v| matches!(v, Sample::Block)));
                assert!(Sample::ALL.iter().any(|v| matches!(v, Sample::Bar)));
                assert!(Sample::ALL.iter().any(|v| matches!(v, Sample::Underline)));
            }

            #[test]
            fn trait_impl_all_matches_inherent_all() {
                // The shikumi git dep is present, so the impl half is
                // exercised: the trait-associated ALL must equal the
                // inherent ALL (both enumerate every variant).
                assert_eq!(<Sample as ::shikumi::ClosedAxis>::ALL, Sample::ALL);
            }
        }
    }
}

/// Smoke test for a VerificationMatrix macro crate: import both macros,
/// declare a 3-row table, drive a passing exercise closure through
/// `verification_matrix!`, and gate coverage with `matrix_covers_all!`.
/// Macro names come from the spec so a renamed surface still verifies.
fn render_verification_matrix_smoke(
    extern_name: &str,
    spec: &VerificationMatrixSpec,
) -> TokenStream {
    let extern_id = format_ident!("{extern_name}");
    let matrix_id = format_ident!("{}", spec.matrix_macro);
    let covers_id = format_ident!("{}", spec.covers_macro);
    quote! {
        pub use #extern_id::{#matrix_id, #covers_id};

        #[derive(Debug)]
        pub struct Row {
            pub name: &'static str,
            pub input: u32,
            pub doubled: u32,
        }

        pub const ROWS: &[Row] = &[
            Row { name: "one", input: 1, doubled: 2 },
            Row { name: "two", input: 2, doubled: 4 },
            Row { name: "three", input: 3, doubled: 6 },
        ];

        #matrix_id! {
            name = every_row_doubles,
            rows = ROWS,
            run = |r: &Row| -> ::std::result::Result<(), ::std::string::String> {
                if r.input * 2 == r.doubled {
                    ::std::result::Result::Ok(())
                } else {
                    ::std::result::Result::Err(
                        ::std::format!("{} != {}", r.input * 2, r.doubled),
                    )
                }
            },
        }

        #covers_id! {
            name = rows_cover_all,
            rows = ROWS,
            covers = 3usize,
        }
    }
}

/// Smoke test for a KindRoundTrip derive: a Sample enum using the spec's
/// helper attr + a test asserting the inverse-table property holds (string
/// always; byte too when `with_byte`). Method/attr names come from the
/// spec so a renamed surface still verifies.
fn render_kind_round_trip_smoke(extern_name: &str, spec: &KindRoundTripSpec) -> TokenStream {
    let extern_id = format_ident!("{extern_name}");
    let trait_id = format_ident!("{}", spec.trait_name.0);
    let attr_id = format_ident!("{}", spec.helper_attr);
    let as_str_id = format_ident!("{}", spec.as_str_method);
    let from_str_id = format_ident!("{}", spec.from_str_method);
    if spec.with_byte {
        let as_byte_id = format_ident!("{}", spec.as_byte_method);
        let from_byte_id = format_ident!("{}", spec.from_byte_method);
        quote! {
            use #extern_id::#trait_id;

            #[derive(Debug, PartialEq, Clone, Copy, #trait_id)]
            pub enum Sample {
                #[#attr_id(name = "alpha", byte = 97)]
                Alpha,
                #[#attr_id(name = "beta", alias = "b", byte = 98)]
                Beta,
            }

            #[cfg(test)]
            mod tests {
                use super::*;
                #[test]
                fn string_and_byte_round_trip() {
                    assert_eq!(Sample::Alpha.#as_str_id(), "alpha");
                    assert_eq!(Sample::Alpha.#as_byte_id(), 97u8);
                    assert_eq!(Sample::#from_str_id("b"), Some(Sample::Beta));
                    assert_eq!(Sample::#from_byte_id(98), Some(Sample::Beta));
                    assert_eq!(Sample::#from_str_id("nope"), None);
                    for v in [Sample::Alpha, Sample::Beta] {
                        assert_eq!(Sample::#from_str_id(v.#as_str_id()), Some(v));
                        assert_eq!(Sample::#from_byte_id(v.#as_byte_id()), Some(v));
                    }
                }
            }
        }
    } else {
        quote! {
            use #extern_id::#trait_id;

            #[derive(Debug, PartialEq, Clone, Copy, #trait_id)]
            pub enum Sample {
                #[#attr_id(name = "alpha")]
                Alpha,
                #[#attr_id(name = "beta", alias = "b")]
                Beta,
                Gamma,
            }

            #[cfg(test)]
            mod tests {
                use super::*;
                #[test]
                fn string_round_trip() {
                    assert_eq!(Sample::Alpha.#as_str_id(), "alpha");
                    assert_eq!(Sample::Gamma.#as_str_id(), "Gamma");
                    assert_eq!(Sample::#from_str_id("b"), Some(Sample::Beta));
                    assert_eq!(Sample::#from_str_id("nope"), None);
                    for v in [Sample::Alpha, Sample::Beta, Sample::Gamma] {
                        assert_eq!(Sample::#from_str_id(v.#as_str_id()), Some(v));
                    }
                }
            }
        }
    }
}

