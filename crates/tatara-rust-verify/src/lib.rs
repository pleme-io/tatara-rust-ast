/// Render a smoke-test body given an explicit `VerifierHint`. Used when
/// the catalog entry opts out of inferred classification.
///
/// The contract: every `VerifierHint` variant maps to exactly one
/// `render_*_smoke` function. Adding a new strategy is a 2-step edit
/// (new variant + new match arm here).
fn render_by_hint(hint: VerifierHint, extern_name: &str, trait_name: &str) -> String {
    match hint {
        VerifierHint::CompileOnly => render_compile_only_smoke(extern_name, trait_name),
        VerifierHint::PerFieldGetter => render_getter_smoke(extern_name, trait_name),
        VerifierHint::PerFieldSetter => render_setter_smoke(extern_name, trait_name, ""),
        VerifierHint::PerFieldWithBuilder => {
            render_with_builder_smoke(extern_name, trait_name, "")
        }
        VerifierHint::PerFieldAsMut => render_asmut_smoke(extern_name, trait_name, ""),
        VerifierHint::PerFieldReplace => render_replace_smoke(extern_name, trait_name, ""),
        VerifierHint::PerFieldTake => render_take_smoke(extern_name, trait_name, ""),
        VerifierHint::PerFieldInvalidatingSetter => {
            render_invalidating_setter_smoke(extern_name, trait_name)
        }
        VerifierHint::PerVariantIsVariant => {
            // Existing per-variant smoke is parameterized by template/method_tpl;
            // for hint dispatch we render the canonical predicate body directly.
            render_isvariant_predicate_smoke(extern_name, trait_name)
        }
        VerifierHint::NewtypeImplFrom => render_impl_from_smoke(extern_name, trait_name),
        VerifierHint::NewtypeAsRef => render_asref_newtype_smoke(extern_name, trait_name),
        VerifierHint::NewtypeDeref => render_deref_newtype_smoke(extern_name, trait_name),
        VerifierHint::NewtypeInner => render_inner_newtype_smoke(extern_name, trait_name),
        VerifierHint::EnumFoldAllVariants => render_all_variants_smoke(extern_name, trait_name),
        VerifierHint::EnumFoldVariantCount => render_variant_count_smoke(extern_name, trait_name),
        VerifierHint::EnumFoldVariantNames => render_variant_names_smoke(extern_name, trait_name),
    }
}

/// Canonical InvalidatingSetter smoke — sample struct includes
/// `last_seqno: u64` (the consumer-contract signal field), and marks
/// the two opt-in fields with `#[invalidating_setter]` per the
/// derive's `field_attribute` contract.
fn render_invalidating_setter_smoke(extern_name: &str, trait_name: &str) -> String {
    format!(
        r#"    use {extern_name}::{trait_name};

    #[derive(Default, {trait_name})]
    pub struct Sample {{
        #[invalidating_setter]
        pub host: String,
        #[invalidating_setter]
        pub port: u16,
        pub last_seqno: u64,
    }}

    #[cfg(test)]
    mod tests {{
        use super::*;
        #[test]
        fn invalidating_setters_store_value_and_reset_seqno() {{
            let mut s = Sample::default();
            s.last_seqno = 42;
            s.set_host("h".into());
            assert_eq!(s.host, "h");
            assert_eq!(s.last_seqno, 0, "set_host must reset seqno");

            s.last_seqno = 99;
            s.set_port(443);
            assert_eq!(s.port, 443);
            assert_eq!(s.last_seqno, 0, "set_port must reset seqno");
        }}

        #[test]
        fn signal_field_does_not_get_a_setter() {{
            // If `set_last_seqno` were generated, the trait would
            // shadow direct assignment — but the macro skips the
            // signal field. Confirm by direct access.
            let mut s = Sample::default();
            s.last_seqno = 7;
            assert_eq!(s.last_seqno, 7);
        }}
    }}
"#
    )
}

/// Canonical IsVariant predicate smoke (extracted from `render_per_variant_smoke`'s
/// is-predicate branch so the hint dispatcher can call it directly).
fn render_isvariant_predicate_smoke(extern_name: &str, trait_name: &str) -> String {
    format!(
        r#"    use {extern_name}::{trait_name};

    #[derive({trait_name})]
    pub enum Sample {{
        Started,
        Stopped(String),
        Tick {{ ms: u64 }},
    }}

    #[cfg(test)]
    mod tests {{
        use super::*;
        #[test]
        fn predicate_returns_true_only_for_own_variant() {{
            let s = Sample::Started;
            assert!(s.is_started());
            assert!(!s.is_stopped());
            assert!(!s.is_tick());
        }}
    }}
"#
    )
}

