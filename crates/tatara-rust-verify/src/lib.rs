// Cargo.toml renderer
// ─────────────────────────────────────────────────────────────────────

fn render_cargo_toml<F>(catalog: &MacroCatalogSpec, repo_path: &F) -> String
where
    F: Fn(&str) -> String,
{
    let mut deps = String::new();
    for e in &catalog.entries {
        deps.push_str(&format!(
            "{name} = {{ path = \"{path}\" }}\n",
            name = e.crate_name,
            path = repo_path(&e.crate_name)
        ));
    }
    format!(
        r#"# Generated by tatara-rust-verify.
#
# Re-emitted on every `catalog-instantiate` run; do not edit by hand.

[package]
name        = "consumer-verify"
version     = "0.1.0"
edition     = "2024"
description = "Auto-generated verifier for the {title} catalog."
license     = "MIT"

[lib]
path = "src/lib.rs"

[dependencies]
{deps}"#,
        title = catalog.title,
        deps = deps
    )
}

/// Convenience: produce a `consumer-verify/` `FileEntry` set for direct
/// inclusion in any in-memory file-map representation.
#[must_use]
pub fn build_consumer_verify_files<F>(
    catalog: &MacroCatalogSpec,
    repo_path: F,
) -> Vec<FileEntry>
where
    F: Fn(&str) -> String,
{
    build_consumer_verify(catalog, repo_path).files
}

