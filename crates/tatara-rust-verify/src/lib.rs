fn render_newtype_smoke(extern_name: &str, spec: &NewtypeDeriveSpec) -> String {
    let trait_name = &spec.trait_name.0;
    let tpl = spec.impl_template.to_lowercase();
    // Same classify-by-substring pattern as per_field: each known
    // newtype derive emits a specialized smoke; unknown templates fall
    // back to compile-only.
    if tpl.contains("from<#inner_ty>") && tpl.contains("from<#self_name>") {
        render_impl_from_smoke(extern_name, trait_name)
    } else if tpl.contains("asref<#inner_ty>") {
        render_asref_newtype_smoke(extern_name, trait_name)
    } else if tpl.contains("deref for #self_name") {
        render_deref_newtype_smoke(extern_name, trait_name)
    } else if tpl.contains("pub fn inner") && tpl.contains("pub fn into_inner") {
        render_inner_newtype_smoke(extern_name, trait_name)
    } else {
        render_newtype_compile_only_smoke(extern_name, trait_name)
    }
}

fn render_impl_from_smoke(extern_name: &str, trait_name: &str) -> String {
    format!(
        r#"    use {extern_name}::{trait_name};

    #[derive({trait_name})]
    pub struct Sample(pub i32);

    #[cfg(test)]
    mod tests {{
        use super::*;
        #[test]
        fn from_inner_constructs_wrapper() {{
            let w: Sample = 42i32.into();
            assert_eq!(w.0, 42);
        }}
        #[test]
        fn from_wrapper_extracts_inner() {{
            let w = Sample(7);
            let n: i32 = w.into();
            assert_eq!(n, 7);
        }}
    }}
"#
    )
}

